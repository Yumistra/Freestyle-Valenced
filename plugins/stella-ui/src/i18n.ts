/** 숫자나 이름이 들어간 글 */
const PATTERNS: [RegExp, (m: RegExpExecArray) => string][] = [
    [/^안 읽은 대화가 (\d+)개 있어요\.$/, m => `You have ${m[1]} unread conversation${m[1] === '1' ? '' : 's'}.`],
    [/^(.+) 님이 입력 중…$/, m => `${m[1]} ${m[1].includes(',') ? 'are' : 'is'} typing…`],
    [/^(.+) 님이 스레드를 시작했어요$/, m => `${m[1]} started a thread`],
    [/^(.+) 님이 들어왔어요$/, m => `${m[1]} joined`],
    [/^(.+) 에게 답장$/, m => `Replying to ${m[1]}`],
    [/^(.+) 에게 메시지 보내기$/, m => `Message ${m[1]}`],
    [/^(#.*) 에 메시지 보내기$/, m => `Message ${m[1]}`],
    [/^(#.*) 채널$/, m => `${m[1]} channel`],
    [/^메시지 (\d+)개$/, m => `${m[1]} message${m[1] === '1' ? '' : 's'}`],
    [/^파일 (\d+)개$/, m => `${m[1]} file${m[1] === '1' ? '' : 's'}`],
    [/^파일은 (\d+)개까지 보낼 수 있어요$/, m => `You can send up to ${m[1]} files`],
    [/^(\d+)개 찾음$/, m => `${m[1]} found`],
    [/^(\d+)명$/, m => `${m[1]} members`],
    [/^친구 신청이 (\d+)개 와 있어요$/, m => `You have ${m[1]} friend request${m[1] === '1' ? '' : 's'}`],
    [/^같이 있는 서버 (\d+)개$/, m => `${m[1]} mutual server${m[1] === '1' ? '' : 's'}`],
    [/^차단한 사람 (\d+)명$/, m => `Blocked (${m[1]})`],
    [/^가진 것 (\d+)$/, m => `Owned ${m[1]}`],
    [/^보상: (.*)$/, m => `Reward: ${m[1]}`],
    [/^(.*) 까지$/, m => `Until ${m[1]}`],
    [/^\[파일\] (.*)$/, m => `[File] ${m[1]}`],
    [/^\[스티커\] (.*)$/, m => `[Sticker] ${m[1]}`],
    [/^(\d+)(초|분|시간|일|달|년) (전|후)$/, m => {
        const unit = { 초: 'second', 분: 'minute', 시간: 'hour', 일: 'day', 달: 'month', 년: 'year' }[m[2]]!
        const word = `${m[1]} ${unit}${m[1] === '1' ? '' : 's'}`
        return m[3] === '전' ? `${word} ago` : `in ${word}`
    }],
    [/^온라인 (\d+)명(.*)$/, m => `Online ${m[1]}${m[2].replace(/, 전체 (\d+)명/, ', $1 total').replace(', 불러온 멤버만 보여요', ', only loaded members shown')}`],
    [/^(.+?), (\d+)\/(\d+)분$/, m => `${tr(m[1])}, ${m[2]}/${m[3]} min`],
    [/^(.+)하지 못했어요: (.*)$/, m => `Couldn't ${m[1] === '고정' ? 'pin' : m[1] === '고정 해제' ? 'unpin' : m[1] === '검색' ? 'search' : m[1]}: ${m[2]}`],
    [/^(.+)(을|를) (불러오지|바꾸지|받지|만들지|고르지) 못했어요: (.*)$/, m => {
        const what: Record<string, string> = { 퀘스트: 'quests', 상점: 'the shop', '고정 메시지': 'pinned messages', 설정: 'the setting', 꾸미기: 'the decoration', '알림 설정': 'notification settings', '초대 링크': 'the invite link', 파일: 'files' }
        const verb: Record<string, string> = { 불러오지: 'load', 바꾸지: 'change', 받지: 'accept', 만들지: 'create', 고르지: 'pick' }
        return `Couldn't ${verb[m[3]]} ${what[m[1]] ?? m[1]}: ${m[4]}`
    }],
    [/^불러오지 못했어요: (.*)$/, m => `Couldn't load: ${m[1]}`],
    [/^검색하지 못했어요: (.*)$/, m => `Couldn't search: ${m[1]}`],
]

/** 한국어 글을 지금 언어로 */
export function tr(text: string): string {
    if (!text || korean()) return text
    const hit = EN[text]
    if (hit !== undefined) return hit
    if (!/[가-힣]/.test(text)) return text
    for (const [re, make] of PATTERNS) {
        const m = re.exec(text)
        if (m) return make(m)
    }
    return text
}
